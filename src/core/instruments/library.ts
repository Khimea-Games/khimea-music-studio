export function getInstrumentById(id: string): InstrumentDefinition {
  const clean = id.toLowerCase();
  return (
    INSTRUMENT_LIBRARY.find((inst) => inst.id === clean) ||
    INSTRUMENT_LIBRARY.find((inst) => clean.includes(inst.id) || inst.id.includes(clean)) ||
    INSTRUMENT_LIBRARY[0]
  );
}

export function getInstrumentsByFamily(family: string): InstrumentDefinition[] {
  return INSTRUMENT_LIBRARY.filter((inst) => inst.family === family);
}
